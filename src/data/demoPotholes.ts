/** Simple asphalt + pothole SVG placeholders so the UI works offline. */
function roadPhoto(seed: number, label: string): string {
  const hues = [35, 28, 42, 22, 48]
  const h = hues[seed % hues.length]
  const cx = 40 + (seed % 5) * 8
  const cy = 45 + (seed % 4) * 6
  const rx = 18 + (seed % 3) * 4
  const ry = 10 + (seed % 3) * 3
  const svg = `
<svg xmlns="http://www.w3.org/2000/svg" width="640" height="400" viewBox="0 0 640 400">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="hsl(${h},12%,28%)"/>
      <stop offset="100%" stop-color="hsl(${h},10%,18%)"/>
    </linearGradient>
  </defs>
  <rect width="640" height="400" fill="url(#g)"/>
  <g stroke="hsl(${h},8%,35%)" stroke-width="2" opacity="0.35">
    <line x1="0" y1="80" x2="640" y2="70"/>
    <line x1="0" y1="160" x2="640" y2="145"/>
    <line x1="0" y1="240" x2="640" y2="255"/>
    <line x1="0" y1="320" x2="640" y2="310"/>
  </g>
  <ellipse cx="${cx * 4}" cy="${cy * 3.5}" rx="${rx * 3}" ry="${ry * 2.5}" fill="#1a1a1a" opacity="0.85"/>
  <ellipse cx="${cx * 4 + 12}" cy="${cy * 3.5 + 4}" rx="${rx * 1.6}" ry="${ry * 1.2}" fill="#0d0d0d"/>
  <rect x="24" y="24" width="200" height="36" rx="8" fill="rgba(0,0,0,0.45)"/>
  <text x="36" y="48" fill="#fff" font-family="system-ui,sans-serif" font-size="16" font-weight="600">${label}</text>
  <rect x="${cx * 4 - rx * 3 - 8}" y="${cy * 3.5 - ry * 2.5 - 8}" width="${rx * 6 + 16}" height="${ry * 5 + 16}" fill="none" stroke="#22c55e" stroke-width="3" rx="4"/>
</svg>`.trim()
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
}

